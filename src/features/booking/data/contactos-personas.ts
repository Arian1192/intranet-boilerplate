function normalizar(texto: string): string {
  return texto
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '');
}

export function filtrarPersonas(lista: PersonaContacto[], texto: string): PersonaContacto[] {
  if (!texto.trim()) return lista;
  const aguja = normalizar(texto);
  return lista.filter(
    (p) =>
      normalizar(p.nombre).includes(aguja) ||
      normalizar(p.email).includes(aguja) ||
      normalizar(p.organizacion ?? '').includes(aguja)
  );
}
